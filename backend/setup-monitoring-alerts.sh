- **Channel**: #alerts-critical (for critical alerts)
- **Webhook**: Configured during setup

### Alert Severities
- **Critical**: Immediate notification (email + Slack)
- **Warning**: Email only, 2-hour repeat interval
- **Info**: Business metrics, 4-hour repeat interval

## Alert Categories

### Application Health
- Application down
- High error rate (>10%)
- High response time (>1s)
- Database connection failures

### Infrastructure
- High CPU usage (>80%)
- High memory usage (>85%)
- Low disk space (>90% critical, >80% warning)

### Database
- PostgreSQL down
- Too many connections (>150)
- Slow queries (>0.5s avg)
- Replication lag (>60s)

### Business Metrics
- Low user activity
- High chatbot usage
- Payment failures
- User registration spikes

### Security
- High failed login rate
- Suspicious API usage
- SSL certificate expiration

## Customization

### Adding New Alerts
1. Edit \`monitoring/alert-rules.yml\`
2. Add new alert rules
3. Restart Prometheus: \`docker-compose restart prometheus\`

### Modifying Notification Channels
1. Edit \`monitoring/alertmanager.yml\`
2. Update receiver configurations
3. Restart Alertmanager: \`docker-compose restart alertmanager\`

### Custom Email Templates
1. Edit \`/etc/alertmanager/templates/email.tmpl\`
2. Restart Alertmanager

## Troubleshooting

### Common Issues

#### 1. Email Not Sending
- Check Gmail App Password
- Verify SMTP settings
